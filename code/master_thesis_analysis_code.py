def apply_thesis_style(
    fig,
    title_size=30,
    axis_title_size=24,
    tick_size=18,
    legend_size=18,
    title_x=0.5
):
    """Apply consistent thesis style."""
    fig.update_layout(
        font=dict(
            family=PLOT_FONT,
            size=tick_size,
            color="black"
        ),
        title=dict(
            font=dict(
                family=PLOT_FONT,
                size=title_size,
                color="black"
            ),
            x=title_x,
            xanchor="center"
        ),
        legend=dict(
            font=dict(
                family=PLOT_FONT,
                size=legend_size,
                color="black"
            ),
            title_font=dict(
                family=PLOT_FONT,
                size=legend_size,
                color="black"
            )
        ),
        paper_bgcolor="white",
        plot_bgcolor="white"
    )

    fig.update_xaxes(
        title_font=dict(family=PLOT_FONT, size=axis_title_size, color="black"),
        tickfont=dict(family=PLOT_FONT, size=tick_size, color="black"),
        showline=True,
        linewidth=1,
        linecolor="black",
        mirror=False,
        ticks="outside",
        gridcolor="rgba(0,0,0,0.10)"
    )

    fig.update_yaxes(
        title_font=dict(family=PLOT_FONT, size=axis_title_size, color="black"),
        tickfont=dict(family=PLOT_FONT, size=tick_size, color="black"),
        showline=True,
        linewidth=1,
        linecolor="black",
        mirror=False,
        ticks="outside",
        gridcolor="rgba(0,0,0,0.10)"
    )

    return fig


